# 重建契约 API 等级基线（新增 public API 并把 SRContract.ApiLevel +1 后运行一次）。
$ErrorActionPreference = 'Stop'
$Root = Split-Path -Parent $PSScriptRoot
$dir = Join-Path $Root 'SR_UCH\Contracts'
$api = 0
$src = [IO.File]::ReadAllText((Join-Path $dir 'Contracts.cs'))
$m = [regex]::Match($src, 'public\s+const\s+int\s+ApiLevel\s*=\s*(\d+)')
if ($m.Success) { $api = [int]$m.Groups[1].Value }
$members = 0
foreach ($f in Get-ChildItem -LiteralPath $dir -Filter '*.cs' -File) {
    foreach ($l in [IO.File]::ReadAllLines($f.FullName)) {
        if ($l -match '^\s*public\s') { $members++ }
    }
}
$out = Join-Path $PSScriptRoot 'api_level.txt'
$txt = "# contract API level baseline (generated by update-api-level.ps1)`n# format: ApiLevel=<n> members=<public declarations>`nApiLevel=$api members=$members`n"
[IO.File]::WriteAllText($out, $txt, (New-Object System.Text.UTF8Encoding($false)))
Write-Host ('  [ OK ] ApiLevel=' + $api + ' members=' + $members)
